/// The handler takes the token TTL and the initData max age from the state's config. `test_config` holds the
/// built-in defaults (1800 / 86 400), so only a state with other values can tell a read field from a literal.
#[tokio::test]
async fn auth_honours_configured_ttl_and_max_age() {
    let all = vectors();
    let (ttl, max_age) = (900, 3600);
    let db = common::TestDb::create().await;
    let mut cfg = common::test_config(&db);
    cfg.token_ttl_secs = ttl;
    cfg.initdata_max_age_secs = max_age;
    let st = match AppState::new(cfg).await {
        Ok(st) => st.with_clock(Arc::new(FixedClock(all.now))),
        Err(e) => panic!("state with TTL {ttl} / max age {max_age}: {e}"),
    };
    let mut failures = Vec::new();
    // `valid` is 100 s old: fresh under a 3600 s max age.
    let reply = post_auth(&st, JSON, auth_body(&vector(&all, "valid").init_data)).await;
    if reply.status == StatusCode::OK {
        let json = body_json(&reply);
        let exp = all.now + ttl;
        let expires_at = json["expiresAt"].as_i64();
        if expires_at != Some(exp) {
            failures.push(format!(
                "valid: expiresAt: expected now+{ttl} = {exp}, got {expires_at:?}"
            ));
        }
        let token = json["token"].as_str().unwrap_or("");
        if !token.starts_with(&format!("v1.1001.{exp}.")) {
            failures.push(format!(
                "valid: token: expected v1.1001.{exp}.<tag>, got {token:?}"
            ));
        }
        failures.extend(token_failure(&st, "valid", &json, all.now, 1001));
    } else {
        failures.push(format!(
            "valid: expected 200, got {} {}",
            reply.status.as_u16(),
            body_text(&reply)
        ));
    }
    // `age_at_limit` is 86 400 s old: expired under 3600 here, accepted under the default 86 400 in
    // `auth_returns_token_for_valid_initdata`; the pair leaves no literal max age that passes both.
    let reply = post_auth(
        &st,
        JSON,
        auth_body(&vector(&all, "age_at_limit").init_data),
    )
    .await;
    failures.extend(expect_reply(
        "age_at_limit",
        &reply,
        401,
        r#"{"error":"initdata_expired"}"#,
    ));
    report(&failures);
}

#[tokio::test]
async fn auth_malformed_body_400() {
    let all = vectors();
    let (st, _db) = auth_state(&all).await;
    let valid = auth_body(&vector(&all, "valid").init_data);
    let bad_request = r#"{"error":"bad_request"}"#;
    let mut failures = Vec::new();
    let cases = [
        ("non-JSON body", JSON, "initData=abc".to_owned()),
        ("empty object", JSON, "{}".to_owned()),
        (
            "initData not a string",
            JSON,
            r#"{"initData":5}"#.to_owned(),
        ),
        ("text/plain content type", "text/plain", valid.clone()),
    ];
    for (case, content_type, body) in cases {
        let reply = post_auth(&st, content_type, body).await;
        failures.extend(expect_reply(case, &reply, 400, bad_request));
    }
    let control = post_auth(&st, JSON, valid).await;
    if control.status != StatusCode::OK {
        failures.push(format!(
            "valid body (control): expected 200, got {}",
            control.status.as_u16()
        ));
    }
    report(&failures);
}

/// More than 4096 bytes of initData is a bad request; exactly 4096 reaches the validator.
#[tokio::test]
async fn auth_initdata_over_4k_400() {
    let all = vectors();
    let (st, _db) = auth_state(&all).await;
    let valid = &vector(&all, "valid").init_data;
    // An unsigned padding field: whatever its length, the validator answers initdata_invalid.
    let padded = |len: usize| {
        let fill = "a".repeat(len - valid.len() - "&pad=".len());
        format!("{valid}&pad={fill}")
    };
    let mut failures = Vec::new();
    for (case, len, status, body) in [
        ("4097 bytes", 4097, 400, r#"{"error":"bad_request"}"#),
        (
            "4096 bytes (control)",
            4096,
            401,
            r#"{"error":"initdata_invalid"}"#,
        ),
    ] {
        let init_data = padded(len);
        assert_eq!(init_data.len(), len, "{case}: padding arithmetic");
        let reply = post_auth(&st, JSON, auth_body(&init_data)).await;
        failures.extend(expect_reply(case, &reply, status, body));
    }
    report(&failures);
}

/// Two logins of one user: one row, `created_at` from the first, `last_seen_at` from the second.
#[tokio::test]
async fn auth_upserts_user_once() {
    let all = vectors();
    let (st, _db) = auth_state(&all).await;
    let body = auth_body(&vector(&all, "valid").init_data);
    let later = st.clone().with_clock(Arc::new(FixedClock(all.now + 100)));
    let mut failures = Vec::new();
    for (case, state) in [("first login", &st), ("second login", &later)] {
        let reply = post_auth(state, JSON, body.clone()).await;
        if reply.status != StatusCode::OK {
            failures.push(format!(
                "{case}: expected 200, got {} {}",
                reply.status.as_u16(),
                body_text(&reply)
            ));
        }
    }
    let rows = user_rows(&st).await;
    let want = vec![(
        1001,
        "Ann".to_owned(),
        Some("ru".to_owned()),
        all.now,
        all.now + 100,
    )];
    if rows != want {
        failures.push(format!(
            "users rows for 1001: expected {want:?}, got {rows:?}"
        ));
    }
    report(&failures);
}

/// A JSON body of exactly `len` bytes whose initData is long enough to be refused by the 4 KB rule.
fn body_of_len(len: usize) -> String {
    let empty = auth_body("");
    let body = auth_body(&"a".repeat(len - empty.len()));
    assert_eq!(body.len(), len, "body length arithmetic");
    body
}

/// The 16 KB default body limit: 17 408 bytes is 413; 16 000 bytes passes the limit and is refused later (400).
#[tokio::test]
async fn auth_body_over_16k_413() {
    let all = vectors();
    let (st, _db) = auth_state(&all).await;
    let mut failures = Vec::new();
    for (case, len, status, body) in [
        (
            "17 408-byte body",
            17_408,
            413,
            r#"{"error":"payload_too_large"}"#,
        ),
        (
            "16 000-byte body (control)",
            16_000,
            400,
            r#"{"error":"bad_request"}"#,
        ),
    ] {
        let reply = post_auth(&st, JSON, body_of_len(len)).await;
        failures.extend(expect_reply(case, &reply, status, body));
    }
    report(&failures);
}
