/// The HMAC runs over decoded values: `%xx` (Cyrillic, `&`, `=`, `+`, `%`) and `+` as a space.
#[test]
fn initdata_url_encoded_values() {
    let all = vectors();
    let mut failures: Vec<String> = ["encoded", "plus_as_space"]
        .iter()
        .filter_map(|name| check_vector(&all, vector(&all, name)))
        .collect();
    // Pinned here as literals too, so a fixture that encodes and expects the same wrong text cannot pass.
    for (name, want) in [
        ("encoded", "Анна-Мария & Co = 1+1 = 100%"),
        ("plus_as_space", "Ann Lee"),
    ] {
        match validate(&all, vector(&all, name)) {
            Ok(data) if data.user.first_name == want => {}
            got => failures.push(format!("{name}: expected first_name {want:?}, got {got:?}")),
        }
    }
    report(&failures);
}

