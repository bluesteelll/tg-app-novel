/// `tests/fixtures/initdata_vectors.json`, generated by `sign_initdata.mjs --write`.
#[derive(Deserialize)]
struct Vectors {
    bot_token: String,
    max_age_secs: i64,
    now: i64,
    vectors: Vec<Vector>,
}

#[derive(Deserialize)]
struct Vector {
    name: String,
    init_data: String,
    /// `ok`, or the `InitDataError` variant name.
    expect: String,
    /// The verified user an `ok` vector yields.
    #[serde(default)]
    user: Option<ExpectedUser>,
}

#[derive(Deserialize)]
struct ExpectedUser {
    id: i64,
    first_name: String,
    language_code: Option<String>,
}

/// Every vector the signer writes; `initdata_all_vectors_match_expectations` checks the file holds exactly these.
const VECTOR_COUNT: usize = 24;

fn vectors() -> Vectors {
    let all: Vectors =
        serde_json::from_str(include_str!("../fixtures/initdata_vectors.json")).unwrap();
    assert_eq!(
        all.bot_token,
        common::TEST_BOT_TOKEN,
        "bot_token mismatch: the vectors are not signed with the test state's bot token"
    );
    all
}

fn vector<'a>(all: &'a Vectors, name: &str) -> &'a Vector {
    all.vectors
        .iter()
        .find(|v| v.name == name)
        .unwrap_or_else(|| panic!("vector {name} missing from initdata_vectors.json"))
}

fn validate(all: &Vectors, v: &Vector) -> Result<InitData, InitDataError> {
    validate_init_data(&v.init_data, &all.bot_token, all.now, all.max_age_secs)
}

/// `None` when the validator's outcome is the vector's `expect` (for `ok`: also its user), else the failure line.
fn check_vector(all: &Vectors, v: &Vector) -> Option<String> {
    let got = validate(all, v);
    match (v.expect.as_str(), &got) {
        ("ok", Ok(data)) => {
            let Some(want) = &v.user else {
                return Some(format!("{}: an ok vector without a user", v.name));
            };
            let user = &data.user;
            let same = user.id.0 == want.id
                && user.first_name == want.first_name
                && user.language_code == want.language_code;
            (!same).then(|| {
                format!(
                    "{}: expected user ({}, {:?}, {:?}), got {user:?}",
                    v.name, want.id, want.first_name, want.language_code
                )
            })
        }
        ("ok", Err(e)) => Some(format!("{}: expected Ok, got Err({e:?})", v.name)),
        (want, Err(e)) if format!("{e:?}") == want => None,
        (want, _) => Some(format!("{}: expected {want}, got {got:?}", v.name)),
    }
}

fn report(failures: &[String]) {
    assert!(
        failures.is_empty(),
        "{} failures:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

fn check_named(names: &[&str]) {
    let all = vectors();
    let failures: Vec<String> = names
        .iter()
        .filter_map(|name| check_vector(&all, vector(&all, name)))
        .collect();
    report(&failures);
}

