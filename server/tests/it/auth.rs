#[test]
fn initdata_all_vectors_match_expectations() {
    let all = vectors();
    let mut failures = Vec::new();
    if all.vectors.len() != VECTOR_COUNT {
        failures.push(format!(
            "vector count: expected {VECTOR_COUNT}, got {}",
            all.vectors.len()
        ));
    }
    let mut names: Vec<&str> = all.vectors.iter().map(|v| v.name.as_str()).collect();
    names.sort_unstable();
    names.dedup();
    if names.len() != all.vectors.len() {
        failures.push("vector names are not unique".to_owned());
    }
    failures.extend(all.vectors.iter().filter_map(|v| check_vector(&all, v)));
    report(&failures);
}

/// The function the dev signer builds initData with: drops only `hash` (`signature` stays), sorts by key.
#[test]
fn initdata_dcs_sorts_and_drops_only_hash() {
    let pairs = [("b", "2"), ("hash", "x"), ("signature", "s"), ("a", "1")]
        .map(|(k, v)| (k.to_owned(), v.to_owned()));
    let got = data_check_string(&pairs);
    assert_eq!(got, "a=1\nb=2\nsignature=s", "data_check_string");
}

/// A fixed issue time for the token tests (unix seconds).
const T0: i64 = 1_790_000_000;
/// The token TTL of the test config (`TOKEN_TTL_SECS`).
const TTL: i64 = 1800;
/// The token key of the token tests.
const KEY_A: [u8; 32] = [7; 32];

/// The token format of PP "Token format", computed here with hmac directly, independent of `issue_token`:
/// `v1.<uid>.<exp>.<hex HMAC-SHA256(key, "v1.<uid>.<exp>")>`.
fn reference_token(key: &[u8; 32], uid: &str, exp: &str) -> String {
    let signed = format!("v1.{uid}.{exp}");
    let mut mac = Hmac::<Sha256>::new_from_slice(key).unwrap();
    mac.update(signed.as_bytes());
    format!("{signed}.{}", hex::encode(mac.finalize().into_bytes()))
}

#[test]
fn token_roundtrip() {
    let key = TokenKey::new(KEY_A);
    let (token, exp) = issue_token(&key, UserId(1001), T0, TTL);
    let mut failures = Vec::new();
    if exp != T0 + TTL {
        failures.push(format!("exp: expected now+{TTL} = {}, got {exp}", T0 + TTL));
    }
    let want = reference_token(&KEY_A, "1001", &(T0 + TTL).to_string());
    if token != want {
        failures.push(format!("token: expected {want:?}, got {token:?}"));
    }
    for (case, now) in [("at issue", T0), ("one second before exp", T0 + TTL - 1)] {
        let got = verify_token(&key, &want, now);
        if got != Ok(UserId(1001)) {
            failures.push(format!(
                "verify {case}: expected Ok(UserId(1001)), got {got:?}"
            ));
        }
    }
    report(&failures);
}

#[test]
fn token_rejects_tampered_parts() {
    let key = TokenKey::new(KEY_A);
    let exp = T0 + TTL;
    let token = reference_token(&KEY_A, "1001", &exp.to_string());
    let tag = token.rsplit('.').next().unwrap().to_owned();
    // Flip the first hex digit: still 64 hex chars, a different MAC.
    let flipped = format!(
        "{}{}",
        if tag.starts_with('0') { '1' } else { '0' },
        &tag[1..]
    );
    let cases: Vec<(&str, String, Result<UserId, TokenError>)> = vec![
        ("untampered control", token.clone(), Ok(UserId(1001))),
        (
            "uid 1001 -> 1002",
            format!("v1.1002.{exp}.{tag}"),
            Err(TokenError::BadMac),
        ),
        (
            "uid written +1001",
            format!("v1.+1001.{exp}.{tag}"),
            Err(TokenError::BadMac),
        ),
        (
            "exp changed",
            format!("v1.1001.{}.{tag}", exp + 3600),
            Err(TokenError::BadMac),
        ),
        (
            "tag flipped",
            format!("v1.1001.{exp}.{flipped}"),
            Err(TokenError::BadMac),
        ),
        (
            "v2 prefix",
            format!("v2.1001.{exp}.{tag}"),
            Err(TokenError::Malformed),
        ),
        (
            "3 parts",
            format!("v1.1001.{tag}"),
            Err(TokenError::Malformed),
        ),
        (
            "5 parts",
            format!("v1.1001.{exp}.0.{tag}"),
            Err(TokenError::Malformed),
        ),
        (
            "non-hex tag",
            format!("v1.1001.{exp}.{}", "z".repeat(64)),
            Err(TokenError::Malformed),
        ),
        (
            "short tag",
            format!("v1.1001.{exp}.{}", &tag[..62]),
            Err(TokenError::Malformed),
        ),
        ("empty", String::new(), Err(TokenError::Malformed)),
    ];
    let mut failures = Vec::new();
    for (case, t, want) in cases {
        let got = verify_token(&key, &t, T0);
        if got != want {
            failures.push(format!("{case}: expected {want:?}, got {got:?}"));
        }
    }
    let other = TokenKey::new([8; 32]);
    let got = verify_token(&other, &token, T0);
    if got != Err(TokenError::BadMac) {
        failures.push(format!(
            "key B on a key-A token: expected Err(BadMac), got {got:?}"
        ));
    }
    report(&failures);
}

/// A test-only router: the extractor is exercised without a production route that needs a token.
fn probe_router(st: AppState) -> Router {
    Router::new()
        .route(
            "/probe",
            get(|AuthUser(user): AuthUser| async move { user.0.to_string() }),
        )
        .with_state(st)
}

/// `GET /probe` with an optional `Authorization` header: the status and the body text.
async fn probe(st: &AppState, authorization: Option<&str>) -> (StatusCode, String) {
    let mut req = Request::get("/probe");
    if let Some(value) = authorization {
        req = req.header(AUTHORIZATION, value);
    }
    let response = probe_router(st.clone())
        .oneshot(req.body(Body::empty()).unwrap())
        .await
        .unwrap();
    let status = response.status();
    let body = response.into_body().collect().await.unwrap().to_bytes();
    (status, String::from_utf8_lossy(&body).into_owned())
}

/// Probes every case and collects the mismatches; `want` is (status, exact body).
async fn probe_cases(st: &AppState, cases: &[(&str, Option<String>, u16, &str)]) -> Vec<String> {
    let mut failures = Vec::new();
    for (case, authorization, status, body) in cases {
        let got = probe(st, authorization.as_deref()).await;
        if got.0.as_u16() != *status || got.1 != *body {
            failures.push(format!(
                "{case}: expected {status} {body}, got {} {}",
                got.0.as_u16(),
                got.1
            ));
        }
    }
    failures
}

/// A migrated state whose clock reads `now`.
async fn state_at(now: i64) -> (AppState, TempDir) {
    let (st, dir) = common::test_state().await;
    (st.with_clock(Arc::new(FixedClock(now))), dir)
}

const TOKEN_MISSING: &str = r#"{"error":"token_missing"}"#;
const TOKEN_INVALID: &str = r#"{"error":"token_invalid"}"#;
const TOKEN_EXPIRED: &str = r#"{"error":"token_expired"}"#;

#[tokio::test]
async fn token_missing_401() {
    let (st, _dir) = state_at(T0).await;
    let (good, _) = issue_token(&st.keys.token, UserId(1001), T0, st.cfg.token_ttl_secs);
    let failures = probe_cases(
        &st,
        &[
            ("no header", None, 401, TOKEN_MISSING),
            (
                "Basic scheme",
                Some("Basic dXNlcjpwYXNz".to_owned()),
                401,
                TOKEN_MISSING,
            ),
            ("scheme only", Some("Bearer".to_owned()), 401, TOKEN_MISSING),
            (
                "valid token (control)",
                Some(format!("Bearer {good}")),
                200,
                "1001",
            ),
            (
                "lowercase scheme (control)",
                Some(format!("bearer {good}")),
                200,
                "1001",
            ),
        ],
    )
    .await;
    report(&failures);
}

#[tokio::test]
async fn token_wrong_key_401() {
    let (st, _dir) = state_at(T0).await;
    let ttl = st.cfg.token_ttl_secs;
    let (other_key, _) = issue_token(&TokenKey::new([8; 32]), UserId(1001), T0, ttl);
    let (good, _) = issue_token(&st.keys.token, UserId(1001), T0, ttl);
    let failures = probe_cases(
        &st,
        &[
            (
                "token of another key",
                Some(format!("Bearer {other_key}")),
                401,
                TOKEN_INVALID,
            ),
            (
                "not a token",
                Some("Bearer abc".to_owned()),
                401,
                TOKEN_INVALID,
            ),
            (
                "valid token (control)",
                Some(format!("Bearer {good}")),
                200,
                "1001",
            ),
        ],
    )
    .await;
    report(&failures);
}

/// `exp > now`: the token is good one second before `exp` and expired at `exp`.
#[tokio::test]
async fn token_expired_401() {
    let (st, _dir) = state_at(T0).await;
    let ttl = st.cfg.token_ttl_secs;
    let (token, exp) = issue_token(&st.keys.token, UserId(1001), T0, ttl);
    let bearer = Some(format!("Bearer {token}"));
    let mut failures = Vec::new();
    if exp != T0 + ttl {
        failures.push(format!("exp: expected {}, got {exp}", T0 + ttl));
    }
    let at_exp = st.clone().with_clock(Arc::new(FixedClock(T0 + ttl)));
    failures.extend(probe_cases(&at_exp, &[("at exp", bearer.clone(), 401, TOKEN_EXPIRED)]).await);
    let before = st.clone().with_clock(Arc::new(FixedClock(T0 + ttl - 1)));
    failures.extend(
        probe_cases(
            &before,
            &[("1 s before exp (control)", bearer, 200, "1001")],
        )
        .await,
    );
    report(&failures);
}
